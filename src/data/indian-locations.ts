export function isValidIndianPinForState(pinInput: string, state: string): { valid: boolean; reason?: string } {
  const pin = pinInput.trim();
  if (!/^[1-9][0-9]{5}$/.test(pin)) {
    return { valid: false, reason: "Enter a valid 6-digit Indian PIN code (e.g. 638001)." };
  }
  const allowedPrefixes = STATE_PIN_PREFIXES[state];
  if (allowedPrefixes && !allowedPrefixes.includes(pin.slice(0, 2))) {
    return {
      valid: false,
      reason: `PIN code ${pin} does not match ${state}. Please enter a valid ${state} PIN code (starts with ${allowedPrefixes.join(", ")}).`,
    };
  }
  return { valid: true };
}

